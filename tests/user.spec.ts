import { test, expect } from "playwright-test-coverage";

test("updateUser", async ({ page }) => {
  const email = `user${Math.floor(Math.random() * 10000)}@jwt.com`;
  const updatedEmail = `updated${email}`;

  await test.step("register user", async () => {
    await page.goto("/");
    await page.getByRole("link", { name: "Register" }).click();
    await page.getByRole("textbox", { name: "Full name" }).fill("pizza diner");
    await page.getByRole("textbox", { name: "Email address" }).fill(email);
    await page.getByRole("textbox", { name: "Password" }).fill("diner");
    await page.getByRole("button", { name: "Register" }).click();

    await page.getByRole("link", { name: "pd" }).click();

    await expect(page.getByRole("main")).toContainText("pizza diner");
  });
  //   edit username
  await test.step("edit username", async () => {
    await page.getByRole("button", { name: "Edit" }).click();
    await expect(page.locator("h3")).toContainText("Edit user");

    await page.getByRole("textbox").first().fill("pizza dinerx");
    await page.getByRole("button", { name: "Update" }).click();

    await page.waitForSelector('[role="dialog"].hidden', { state: "attached" });

    await expect(page.getByRole("main")).toContainText("pizza dinerx");
  });
  // edit email
  await test.step("edit email", async () => {
    await page.getByRole("button", { name: "Edit" }).click();
    await expect(page.locator("h3")).toContainText("Edit user");

    await page.locator('input[type="email"]').click();
    await page.locator('input[type="email"]').fill(`${updatedEmail}`);
    await page.getByRole("button", { name: "Update" }).click();

    await expect(page.getByRole("main")).toContainText(`${updatedEmail}`);
  });
  // edit password
  await test.step("edit password", async () => {
    await page.getByRole("button", { name: "Edit" }).click();
    await expect(page.locator("h3")).toContainText("Edit user");

    await page.locator("#password").click();
    await page.locator("#password").fill("NewPassword");
    await page.getByRole("button", { name: "Update" }).click();
  });

  //   edits are persistent
  await test.step("tests are persistent", async () => {
    await page.getByRole("link", { name: "Logout" }).click();
    await page.getByRole("link", { name: "Login" }).click();

    await page
      .getByRole("textbox", { name: "Email address" })
      .fill(updatedEmail);
    await page.getByRole("textbox", { name: "Password" }).fill("NewPassword");
    await page.getByRole("button", { name: "Login" }).click();

    await page.getByRole("link", { name: "pd" }).click();

    await expect(page.getByRole("main")).toContainText("pizza dinerx");
  });
});

// Test same thing but with franchisee role (generated by gemini)

test("updateUser - Mocked Franchisee", async ({ page }) => {
  // In-memory user state
  let currentUser = {
    id: 101,
    name: "Pizza Franchisee",
    email: "franchisee@jwt.com",
    roles: [{ role: "franchisee", object: "pizza" }],
  };

  let token = "mock-jwt-token-franchisee";

  // Mock all /api/auth calls (Login, Session check, Logout)
  await page.route(/\/api\/auth(\?.*)?$/, async (route) => {
    const method = route.request().method();

    if (method === "PUT") {
      // 1. User submits login form
      token = "mock-jwt-token-franchisee";
      await route.fulfill({
        status: 200,
        contentType: "application/json",
        json: { user: currentUser, token },
      });
    } else if (method === "GET") {
      // 2. App verifies active session
      if (token) {
        await route.fulfill({
          status: 200,
          contentType: "application/json",
          json: { user: currentUser },
        });
      } else {
        await route.fulfill({
          status: 401,
          contentType: "application/json",
          json: { message: "unauthorized" },
        });
      }
    } else if (method === "DELETE") {
      // 3. User logs out
      token = "";
      await route.fulfill({
        status: 200,
        contentType: "application/json",
        json: { message: "logout successful" },
      });
    } else {
      await route.continue();
    }
  });

  // Mock user update endpoint (PUT /api/user/:id)
  await page.route(/\/api\/user(\/.*)?$/, async (route) => {
    if (route.request().method() === "PUT") {
      const data = route.request().postDataJSON();
      currentUser = {
        ...currentUser,
        name: data.name ?? currentUser.name,
        email: data.email ?? currentUser.email,
      };

      await route.fulfill({
        status: 200,
        contentType: "application/json",
        json: { user: currentUser },
      });
    } else {
      await route.continue();
    }
  });

  const updatedName = "Pizza Franchisee Updated";
  const updatedEmail = "updated_franchisee@jwt.com";

  // --- 1. Login ---
  await test.step("login as franchisee", async () => {
    await page.goto("/");
    await page.getByRole("link", { name: "Login" }).click();
    await page
      .getByRole("textbox", { name: "Email address" })
      .fill("franchisee@jwt.com");
    await page.getByRole("textbox", { name: "Password" }).fill("password");
    await page.getByRole("button", { name: "Login" }).click();

    // Open profile modal via initials (PF)
    await page.getByRole("link", { name: "pf" }).click();
    await expect(page.getByRole("main")).toContainText("Pizza Franchisee");
    await expect(page.getByRole("main")).toContainText("franchisee@jwt.com");
  });

  // --- 2. Edit Name ---
  await test.step("edit username", async () => {
    await page.getByRole("button", { name: "Edit" }).click();
    await expect(page.locator("h3")).toContainText("Edit user");

    await page.getByRole("textbox").first().fill(updatedName);
    await page.getByRole("button", { name: "Update" }).click();

    await page.waitForSelector('[role="dialog"].hidden', { state: "attached" });
    await expect(page.getByRole("main")).toContainText(updatedName);
  });

  // --- 3. Edit Email ---
  await test.step("edit email", async () => {
    await page.getByRole("button", { name: "Edit" }).click();
    await expect(page.locator("h3")).toContainText("Edit user");

    await page.locator('input[type="email"]').click();
    await page.locator('input[type="email"]').fill(updatedEmail);
    await page.getByRole("button", { name: "Update" }).click();

    await page.waitForSelector('[role="dialog"].hidden', { state: "attached" });
    await expect(page.getByRole("main")).toContainText(updatedEmail);
  });

  // --- 4. Edit Password ---
  await test.step("edit password", async () => {
    await page.getByRole("button", { name: "Edit" }).click();
    await expect(page.locator("h3")).toContainText("Edit user");

    await page.locator("#password").click();
    await page.locator("#password").fill("NewFranchiseePass123!");
    await page.getByRole("button", { name: "Update" }).click();

    await page.waitForSelector('[role="dialog"].hidden', { state: "attached" });
  });

  // --- 5. Verify Edits Persist Across Re-login ---
  await test.step("edits are persistent across re-login", async () => {
    await page.getByRole("link", { name: "Logout" }).click();
    await page.getByRole("link", { name: "Login" }).click();

    await page
      .getByRole("textbox", { name: "Email address" })
      .fill(updatedEmail);
    await page
      .getByRole("textbox", { name: "Password" })
      .fill("NewFranchiseePass123!");
    await page.getByRole("button", { name: "Login" }).click();

    // Updated initials: "Pizza Franchisee Updated" -> "pu"
    await page.getByRole("link", { name: "pu" }).click();

    await expect(page.getByRole("main")).toContainText(updatedName);
    await expect(page.getByRole("main")).toContainText(updatedEmail);
  });
});
